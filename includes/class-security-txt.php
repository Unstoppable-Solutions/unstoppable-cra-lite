<?php
/**
 * Security.txt Generator Class
 *
 * Generates a security.txt file according to RFC 9116.
 * This is genuinely useful and satisfies a real CRA requirement.
 *
 * @package Unstoppable_CRA_Lite
 */

// Prevent direct access.
if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

/**
 * Security.txt Generator Class.
 */
class UCRAL_Security_Txt {

    /**
     * Constructor.
     */
    public function __construct() {
        add_action( 'init', array( $this, 'maybe_serve_security_txt' ) );
        add_action( 'wp_ajax_ucral_save_security_txt', array( $this, 'ajax_save_settings' ) );
    }

    /**
     * Get default settings.
     *
     * @return array
     */
    public static function get_defaults() {
        return array(
            'enabled'         => false,
            'contact_email'   => get_option( 'admin_email' ),
            'contact_url'     => '',
            'encryption_url'  => '',
            'acknowledgments' => '',
            'policy_url'      => '',
            'hiring_url'      => '',
            'expires'         => gmdate( 'Y-m-d', strtotime( '+1 year' ) ),
            'preferred_lang'  => 'en',
        );
    }

    /**
     * Get current settings.
     *
     * @return array
     */
    public static function get_settings() {
        $defaults = self::get_defaults();
        $saved    = get_option( 'ucral_security_txt_settings', array() );
        
        return wp_parse_args( $saved, $defaults );
    }

    /**
     * Save settings.
     *
     * @param array $settings Settings to save.
     * @return bool
     */
    public static function save_settings( $settings ) {
        $sanitized = array(
            'enabled'         => ! empty( $settings['enabled'] ),
            'contact_email'   => sanitize_email( $settings['contact_email'] ?? '' ),
            'contact_url'     => esc_url_raw( $settings['contact_url'] ?? '' ),
            'encryption_url'  => esc_url_raw( $settings['encryption_url'] ?? '' ),
            'acknowledgments' => esc_url_raw( $settings['acknowledgments'] ?? '' ),
            'policy_url'      => esc_url_raw( $settings['policy_url'] ?? '' ),
            'hiring_url'      => esc_url_raw( $settings['hiring_url'] ?? '' ),
            'expires'         => sanitize_text_field( $settings['expires'] ?? '' ),
            'preferred_lang'  => sanitize_text_field( $settings['preferred_lang'] ?? 'en' ),
        );

        return update_option( 'ucral_security_txt_settings', $sanitized );
    }

    /**
     * Generate security.txt content.
     *
     * @return string
     */
    public static function generate_content() {
        $settings = self::get_settings();
        $lines    = array();

        // Comment header.
        $lines[] = '# Security Policy';
        $lines[] = '# Generated by Unstoppable CRA Compliance Checker';
        $lines[] = '# https://securitytxt.org/ | RFC 9116';
        $lines[] = '';

        // Contact (required).
        if ( ! empty( $settings['contact_email'] ) ) {
            $lines[] = 'Contact: mailto:' . $settings['contact_email'];
        }
        if ( ! empty( $settings['contact_url'] ) ) {
            $lines[] = 'Contact: ' . $settings['contact_url'];
        }

        // Expires (required).
        if ( ! empty( $settings['expires'] ) ) {
            $lines[] = 'Expires: ' . gmdate( 'c', strtotime( $settings['expires'] ) );
        }

        // Optional fields.
        if ( ! empty( $settings['encryption_url'] ) ) {
            $lines[] = 'Encryption: ' . $settings['encryption_url'];
        }

        if ( ! empty( $settings['acknowledgments'] ) ) {
            $lines[] = 'Acknowledgments: ' . $settings['acknowledgments'];
        }

        if ( ! empty( $settings['policy_url'] ) ) {
            $lines[] = 'Policy: ' . $settings['policy_url'];
        }

        if ( ! empty( $settings['hiring_url'] ) ) {
            $lines[] = 'Hiring: ' . $settings['hiring_url'];
        }

        if ( ! empty( $settings['preferred_lang'] ) ) {
            $lines[] = 'Preferred-Languages: ' . $settings['preferred_lang'];
        }

        // Canonical (always add).
        $lines[] = 'Canonical: ' . home_url( '/.well-known/security.txt' );

        return implode( "\n", $lines );
    }

    /**
     * Check if security.txt is enabled.
     *
     * @return bool
     */
    public static function is_enabled() {
        $settings = self::get_settings();
        return ! empty( $settings['enabled'] );
    }

    /**
     * Maybe serve security.txt.
     */
    public function maybe_serve_security_txt() {
        if ( ! self::is_enabled() ) {
            return;
        }

        $request_uri = isset( $_SERVER['REQUEST_URI'] ) ? sanitize_text_field( wp_unslash( $_SERVER['REQUEST_URI'] ) ) : '';
        
        // Check for both locations.
        if ( '/.well-known/security.txt' === $request_uri || '/security.txt' === $request_uri ) {
            header( 'Content-Type: text/plain; charset=utf-8' );
            header( 'X-Robots-Tag: noindex' );
            echo self::generate_content(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
            exit;
        }
    }

    /**
     * AJAX handler for saving settings.
     */
    public function ajax_save_settings() {
        check_ajax_referer( 'ucral_security_txt', 'nonce' );

        if ( ! current_user_can( 'manage_options' ) ) {
            wp_send_json_error( array( 'message' => __( 'Permission denied.', 'unstoppable-cra-lite' ) ) );
        }

        $settings = array(
            'enabled'         => isset( $_POST['enabled'] ),
            'contact_email'   => isset( $_POST['contact_email'] ) ? sanitize_email( wp_unslash( $_POST['contact_email'] ) ) : '',
            'contact_url'     => isset( $_POST['contact_url'] ) ? esc_url_raw( wp_unslash( $_POST['contact_url'] ) ) : '',
            'encryption_url'  => isset( $_POST['encryption_url'] ) ? esc_url_raw( wp_unslash( $_POST['encryption_url'] ) ) : '',
            'acknowledgments' => isset( $_POST['acknowledgments'] ) ? esc_url_raw( wp_unslash( $_POST['acknowledgments'] ) ) : '',
            'policy_url'      => isset( $_POST['policy_url'] ) ? esc_url_raw( wp_unslash( $_POST['policy_url'] ) ) : '',
            'hiring_url'      => isset( $_POST['hiring_url'] ) ? esc_url_raw( wp_unslash( $_POST['hiring_url'] ) ) : '',
            'expires'         => isset( $_POST['expires'] ) ? sanitize_text_field( wp_unslash( $_POST['expires'] ) ) : '',
            'preferred_lang'  => isset( $_POST['preferred_lang'] ) ? sanitize_text_field( wp_unslash( $_POST['preferred_lang'] ) ) : 'en',
        );

        self::save_settings( $settings );

        wp_send_json_success( array(
            'message' => __( 'Security.txt settings saved.', 'unstoppable-cra-lite' ),
            'preview' => self::generate_content(),
        ) );
    }

    /**
     * Get security.txt URL.
     *
     * @return string
     */
    public static function get_url() {
        return home_url( '/.well-known/security.txt' );
    }
}

// Initialize.
new UCRAL_Security_Txt();
